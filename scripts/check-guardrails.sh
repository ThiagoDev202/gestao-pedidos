#!/usr/bin/env bash
set -uo pipefail

cd "$(git rev-parse --show-toplevel)" || exit 1
mode="${1:---staged}"
base="${2:-}"
head="${3:-HEAD}"
for ref in "$base" "$head"; do
  case "$ref" in -*) echo "uso: $0 [--staged | --all | --diff <base> [head]]"; exit 2 ;; esac
done
if [ "$mode" = "--diff" ] && [ -z "$base" ]; then echo "uso: $0 [--staged | --all | --diff <base> [head]]"; exit 2; fi
fail=0

report() { echo "✗ $1"; fail=1; }

list_files() {
  if [ "$mode" = "--all" ]; then
    git ls-files -z
  elif [ "$mode" = "--diff" ]; then
    git diff --name-only -z --diff-filter=ACMR "$base"..."$head"
  else
    git diff --cached --name-only -z --diff-filter=ACMR
  fi
}

content_of() {
  if [ "$mode" = "--all" ]; then
    [ -f "$1" ] && grep -I -e '' -- "$1" 2>/dev/null
  elif [ "$mode" = "--diff" ]; then
    git diff -U0 --diff-filter=ACMR "$base"..."$head" -- "$1" | grep -E '^\+[^+]'
  else
    git diff --cached -U0 --diff-filter=ACMR -- "$1" | grep -E '^\+[^+]'
  fi
}

url_cred_re='[a-z][a-z0-9+.-]*://[^/:@[:space:]"'"'"']+:[^@/[:space:]"'"'"']+@'
strong_re='AKIA[0-9A-Z]{16}|-----BEGIN [A-Z ]*PRIVATE KEY-----|gh[pousr]_[A-Za-z0-9]{30,}|xox[baprs]-[A-Za-z0-9-]{10,}'
key_re='(secret|password|passwd|token|api[_-]?key|access[_-]?key)[A-Za-z0-9_]*["'"'"']?[[:space:]]*[:=][[:space:]]*'
quoted_re="${key_re}[\"'][^\"'\$ {]{12,}[\"']"
unquoted_re="${key_re}[A-Za-z0-9_+/=][A-Za-z0-9_+/=-]{15,}"
fallback_re="(secret|password|passwd|token|api[_-]?key|access[_-]?key).*(\|\||\?\?)[[:space:]]*[\"'][^\"' ]{12,}[\"']"
slash_comment_re='^\+[[:space:]]*(//|/\*|\*[[:space:]/]|\*$)|[^:"'"'"'/]//[[:space:]]|/\*'
hash_comment_re='^\+[[:space:]]*#|[[:space:]]#[[:space:]]'
directive_re='eslint-|@ts-|prettier-ignore|istanbul ignore|^\+#!|# syntax=|#pragma|SuppressMessage|<auto-generated'

while IFS= read -r -d '' f; do
  case "$f" in
    *.env.example) ;;
    .env|*/.env|.env.*|*/.env.*|*.pem|*.p8|*.p12|*.key|*.pfx|*.jks|*.keystore)
      report "arquivo proibido no commit: $f"; continue ;;
  esac

  [ "$f" = "scripts/check-guardrails.sh" ] && continue
  added=$(content_of "$f" || true)
  [ -z "$added" ] && continue

  case "$f" in
    *.env.example|*.md) ;;
    *) if hits=$(printf '%s\n' "$added" | grep -nE "$url_cred_re"); then
         report "credencial embutida em URL/DSN em $f (use variável de ambiente):"; echo "$hits" | head -3
       fi ;;
  esac

  if hits=$(printf '%s\n' "$added" | grep -nE "$strong_re"); then
    report "possível segredo em $f:"; echo "$hits" | head -3
  fi
  case "$f" in
    *.env.example|*.md|database/*) ;;
    *) re="($quoted_re)|($fallback_re)"
       case "$f" in
         *.yml|*.yaml|*.env*|*.sh|*Dockerfile|*.toml|*.ini|*.properties) re="($quoted_re)|($unquoted_re)|($fallback_re)" ;;
       esac
       if hits=$(printf '%s\n' "$added" | grep -inE "$re"); then
         report "possível segredo em $f:"; echo "$hits" | head -3
       fi ;;
  esac

  if [ "$mode" != "--all" ]; then
    case "$f" in
      *.ts|*.tsx)
        if hits=$(printf '%s\n' "$added" | grep -E ':\s*any\b|\bas any\b|<any>'); then
          report "\`any\` em código novo em $f (docs/policies/coding.md):"; echo "$hits" | head -3
        fi ;;
    esac

    comment_re=""
    case "$f" in
      *.cs|*.ts|*.tsx|*.js|*.jsx|*.mjs|*.cjs) comment_re="$slash_comment_re" ;;
      *.sh|*.yml|*.yaml|*Dockerfile|.githooks/*) comment_re="$hash_comment_re" ;;
    esac
    if [ -n "$comment_re" ]; then
      if hits=$(printf '%s\n' "$added" | grep -E "$comment_re" | grep -vE "$directive_re"); then
        report "comentário em código novo em $f (o projeto não usa comentários; docs/policies/coding.md):"; echo "$hits" | head -3
      fi
    fi
  fi
done < <(list_files)

if [ "$fail" -eq 0 ]; then
  echo "✓ guardrails OK"
fi
exit "$fail"
